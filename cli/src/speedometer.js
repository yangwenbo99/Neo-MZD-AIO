export const metricClass = name => name === 'none' ? 'hidden' : metrics.find(row => row[0] === name)[2]

export function speedometerFiles (options) {
  const table = Object.fromEntries(metrics.map(([name, element]) => {
    const position = options.bar_layout[name]
    // The runtime uses a zero bottom-row position to hide a metric, not area 2.
    return [element, position[0] === 2 ? [1, 1, 0] : position]
  }))
  const classic = classicFields.map(([key, id, name, starting, unitClass]) => ({
    id, name, starting, unitClass, class: metricClass(key), pos: options.classic_layout[key]
  })).sort((a, b) => a.pos - b.pos)
  const config = `// Generated by mzd-aio-cli\nvar spdBottomRows = ${options.bottom_rows};\nvar spdTbl = ${JSON.stringify(table, null, 2)};\nvar classicSpeedoTmplt = ${JSON.stringify(classic, null, 2)};\nvar overRideSpeed = false;\n`
  const controls = {}
  for (const view of ['bar', 'classic']) {
    controls[view] = { hold: {} }
    for (const binding of bindings) {
      const action = options.controls[view][binding]
      const value = action === 'none' ? 'null' : String(actions[view].indexOf(action))
      if (binding.startsWith('hold_')) controls[view].hold[binding.slice(5)] = value
      else controls[view][binding] = value
    }
  }
  let css = '/* Generated bar speedometer themes */\n'
  for (const [number, palette] of Object.entries(options.bar_themes)) {
    const scope = `#speedBarContainer.theme${number} #vehdataMainDiv`
    css += `${scope} fieldset div, ${scope} [class*="vehDataMain"].pos0 div { color: ${palette.primary}; }\n`
    css += `${scope} [class*="vehDataMain"].pos0 legend .spunit span, ${scope} fieldset { color: ${palette.secondary}; border-color: ${palette.border}; }\n`
  }
  return {
    'config/speedometer/speedometer-config.js': config,
    'config/speedometer/speedometer-controls.js': `var spdBtn = ${JSON.stringify(controls, null, 2)};\n`,
    'config/speedometer/barThemes.css': css
  }
}
